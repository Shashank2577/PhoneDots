package dev.baseplatform.base_models

import android.content.Context
import org.json.JSONArray
import org.json.JSONObject
import java.io.File
import java.io.IOException
import java.io.RandomAccessFile
import java.net.HttpURLConnection
import java.net.URL
import java.nio.channels.FileLock
import java.nio.channels.OverlappingFileLockException
import java.nio.file.Files
import java.nio.file.StandardCopyOption
import java.security.MessageDigest
import java.time.Instant
import java.time.temporal.ChronoUnit

/**
 * The shared model store for native Android apps (Kotlin), protocol v1
 * (docs/MODEL_STORE.md in the base platform). The Flutter apps use the same
 * folder layout, registry and sibling protocol through `base_models`, so a
 * Kotlin app and a Flutter app on one phone share every model.
 *
 * Plain JVM code apart from [storeDir] and [AndroidSiblings]: it runs in unit
 * tests against a temp folder. Every call that touches the network or disk
 * blocks; call it from a background thread or `Dispatchers.IO`.
 *
 * One store per process: the registry and download locks are file locks,
 * which exclude other processes but not two stores in one process. A Flutter
 * app uses the Dart store only; a Kotlin app uses one [SharedModelStore].
 *
 * Do not edit this file in an app: it is synced from baseApp
 * (packages/base_models/android). Change it there and run `./base sync`.
 */
class SharedModelStore(
    val root: File,
    val appId: String,
    val catalog: ModelCatalog,
    private val siblings: SiblingSource? = null,
    private val offline: () -> Boolean = { false },
    private val headersFor: (CatalogFile) -> Map<String, String> = { emptyMap() },
    private val onNetworkBytes: (Long) -> Unit = {},
    /** One line per step (claimed, copied from a sibling, downloading, checksum ok, failed...) for the app's logs page. */
    private val log: (String) -> Unit = {},
) {
    init {
        root.mkdirs()
    }

    // ---------------------------------------------------------------- reading

    /** "Never go online" is on: an SDK installer must only check its folder, never download. */
    fun isOffline(): Boolean = offline()

    fun pathOf(id: String, file: String? = null): File = if (file == null) File(root, id) else File(File(root, id), file)

    /** The registry lists [id] and every file is on disk at its recorded size. */
    fun isReady(id: String): Boolean {
        val spec = catalog.byId(id) ?: return false
        val entry = models().optJSONObject(id) ?: return false
        return filesPresent(spec, entry)
    }

    /** App ids that use [id] on this device. */
    fun users(id: String): Set<String> = models().optJSONObject(id)?.optJSONObject("users")?.keys()?.asSequence()?.toSet() ?: emptySet()

    /** Model ids this app has claimed (including ones whose files went missing). */
    fun claimedByThisApp(): Set<String> {
        val m = models()
        return m.keys().asSequence().filter { m.optJSONObject(it)?.optJSONObject("users")?.has(appId) == true }.toSet()
    }

    /** "network", "sibling" or "bundled" for a ready model; null otherwise. */
    fun sourceOf(id: String): String? {
        val entry = models().optJSONObject(id) ?: return null
        val files = entry.optJSONObject("files")
        if (files == null || files.length() == 0) {
            return if (entry.optBoolean("sdkReady")) entry.optString("sdkSource", "network") else null
        }
        return if (files.keys().asSequence().any { files.optJSONObject(it)?.optString("source") == "network" }) "network" else "sibling"
    }

    /** Bytes of every model in the store, all apps together. */
    fun bytesOnDisk(): Long {
        val m = models()
        var total = 0L
        for (id in m.keys()) {
            val e = m.optJSONObject(id) ?: continue
            e.optJSONObject("files")?.let { f -> for (n in f.keys()) total += f.optJSONObject(n)?.optLong("bytes") ?: 0 }
            total += e.optLong("sdkBytes", 0)
        }
        return total
    }

    /** Another app on this device holds every file of [id] (Android sibling copy, no download). */
    fun inSibling(id: String): Boolean {
        val spec = catalog.byId(id) ?: return false
        if (spec.files.isEmpty()) return false
        val listed = siblingFiles()
        return spec.files.all { f -> listed.any { it.modelId == id && it.file == f.name && matches(f, it) } }
    }

    // ---------------------------------------------------------------- installing

    /**
     * Makes [id] ready for this app: claims the shared copy, copies it from a
     * sibling app, or downloads it (resumable, SHA-256 verified). For an
     * SDK-managed model, [sdkInstall] downloads into the folder it is given.
     *
     * @throws OfflineException when "never go online" blocks a needed download.
     * @throws DownloadCancelled when [cancel] fires.
     */
    fun ensure(
        id: String,
        progress: (Double) -> Unit = {},
        cancel: CancelSignal = CancelSignal(),
        sdkInstall: ((dir: File, progress: (Double) -> Unit) -> Unit)? = null,
    ) {
        val spec = catalog.byId(id) ?: throw IllegalArgumentException("$id is not in the catalog")
        log("$id: needed")
        if (isReady(id) && claim(id)) {
            log("$id: ready, already in the shared store")
            return
        }
        val dir = pathOf(id).apply { mkdirs() }
        RandomAccessFile(File(dir, ".download.lock"), "rw").use { raf ->
            var lock: FileLock? = null
            try {
                // Another app may be downloading the same model: wait, then use its copy.
                while (lock == null) {
                    if (cancel.cancelled) throw DownloadCancelled()
                    lock = try {
                        raf.channel.tryLock()
                    } catch (e: OverlappingFileLockException) {
                        null // This process is installing it on another thread.
                    }
                    if (lock == null) {
                        log("$id: another app is installing it; waiting")
                        Thread.sleep(2000)
                        if (isReady(id) && claim(id)) return
                    }
                }
                if (cancel.cancelled) throw DownloadCancelled()
                if (isReady(id) && claim(id)) return
                log("$id: installing (${if (spec.source == "sdk") "through its SDK" else "${spec.files.size} file(s)"})")
                val recorded = try {
                    if (spec.source == "sdk") installSdk(spec, dir, progress, cancel, sdkInstall) else installFiles(spec, progress, cancel)
                } catch (e: DownloadCancelled) {
                    if (cancel.discard) deletePartials(id)
                    log("$id: cancelled${if (cancel.discard) ", partial download deleted" else ", partial download kept to resume"}")
                    throw e
                } catch (e: Exception) {
                    log("$id: FAILED: ${e.message ?: e.javaClass.simpleName}")
                    throw e
                }
                if (cancel.cancelled) throw DownloadCancelled()
                register(spec, recorded)
                log("$id: ready (${sourceOf(id) ?: "installed"})")
            } finally {
                lock?.release()
            }
        }
    }

    /**
     * Moves files an app downloaded before it used the store into it, so the
     * update doesn't download them again. Each file must match the catalog's
     * size and checksum; returns false (and moves nothing) otherwise.
     */
    fun adopt(id: String, files: Map<String, File>): Boolean {
        val spec = catalog.byId(id) ?: return false
        if (spec.source != "file" || isReady(id) || spec.files.any { files[it.name]?.isFile != true }) return false
        for (f in spec.files) {
            val src = files.getValue(f.name)
            if (f.bytes != null && src.length() != f.bytes) return false
            if (f.sha256 != null && sha256(src) != f.sha256) return false
        }
        val dir = pathOf(id).apply { mkdirs() }
        val recorded = JSONObject()
        for (f in spec.files) {
            val dest = File(dir, f.name)
            Files.move(files.getValue(f.name).toPath(), dest.toPath(), StandardCopyOption.REPLACE_EXISTING)
            recorded.put(f.name, JSONObject().put("bytes", dest.length()).put("sha256", f.sha256 ?: JSONObject.NULL).put("source", "network"))
        }
        register(spec, JSONObject().put("files", recorded))
        return true
    }

    private fun installFiles(spec: CatalogModel, progress: (Double) -> Unit, cancel: CancelSignal): JSONObject {
        val total = spec.files.sumOf { it.bytes ?: 0L }
        var done = 0L
        val files = JSONObject()
        val listed = siblingFiles()
        for (f in spec.files) {
            val dest = pathOf(spec.id, f.name)
            val report = { received: Long -> if (total > 0) progress(((done + received).toDouble() / total).coerceIn(0.0, 1.0)) }
            val fromSibling = copyFromSibling(spec.id, f, dest, listed, cancel)
            if (fromSibling) log("${spec.id}/${f.name}: copied from another app on this phone, checksum ok")
            if (!fromSibling) {
                if (offline()) {
                    log("${spec.id}/${f.name}: not downloaded, \"never go online\" is on")
                    throw OfflineException(spec.name)
                }
                download(f, dest, cancel, report)
            }
            val size = dest.length()
            files.put(f.name, JSONObject().put("bytes", size).put("sha256", f.sha256 ?: JSONObject.NULL).put("source", if (fromSibling) "sibling" else "network"))
            done += f.bytes ?: size
        }
        return JSONObject().put("files", files)
    }

    private fun installSdk(
        spec: CatalogModel,
        dir: File,
        progress: (Double) -> Unit,
        cancel: CancelSignal,
        sdkInstall: ((File, (Double) -> Unit) -> Unit)?,
    ): JSONObject {
        val install = sdkInstall ?: throw IllegalStateException("${spec.name} is installed by its SDK; pass sdkInstall")
        // A sibling's SDK folder, copied file by file into an empty folder, saves
        // the download when the SDK accepts it. Never over weights already here.
        val hadFiles = dir.listFiles()?.any { !it.name.startsWith(".") } == true
        val fromSibling = !hadFiles && copySdkFromSibling(spec.id, dir, cancel)
        if (fromSibling) log("${spec.id}: SDK folder copied from another app on this phone")
        if (!hadFiles && !fromSibling && offline() && !spec.sdkBundled) throw OfflineException(spec.name)
        // The installer is told whether it may go online: after a sibling copy
        // with "never go online" on, it must only check the folder.
        install(dir) { p -> if (cancel.cancelled) throw DownloadCancelled() else progress(p) }
        val bytes = dirSize(dir)
        if (!fromSibling && !spec.sdkBundled && bytes > 0) onNetworkBytes(bytes)
        val out = JSONObject()
            .put("sdkReady", true)
            .put("sdkBytes", bytes)
            .put("sdkSource", if (spec.sdkBundled) "bundled" else if (fromSibling) "sibling" else "network")
        sdkFileList(dir)?.let { out.put("sdkFiles", it) }
        return out
    }

    /** Flat SDK folders only: name → bytes, so siblings can copy them. Null for nested folders. */
    private fun sdkFileList(dir: File): JSONObject? {
        val entries = dir.listFiles()?.filter { !it.name.startsWith(".") } ?: return null
        if (entries.isEmpty() || entries.any { it.isDirectory }) return null
        return JSONObject().apply { entries.forEach { put(it.name, JSONObject().put("bytes", it.length())) } }
    }

    // ---------------------------------------------------------------- releasing

    /** This app stops using [id]; the files go when no app uses it, unless another app is installing it. */
    fun release(id: String) = log("$id: released by this app").let { releaseLocked(id) }

    private fun releaseLocked(id: String) = mutate { models ->
        val entry = models.optJSONObject(id) ?: return@mutate
        entry.optJSONObject("users")?.remove(appId)
        if ((entry.optJSONObject("users")?.length() ?: 0) == 0) {
            models.remove(id)
            deleteDir(id)
        }
    }

    /** Refreshes this app's claim times so other apps know it is still installed. */
    fun touchClaims() = mutate { models ->
        val now = now()
        for (id in models.keys()) models.optJSONObject(id)?.optJSONObject("users")?.let { if (it.has(appId)) it.put(appId, now) }
    }

    /** Forgets apps not seen for [maxAgeDays] (likely uninstalled). Never this app. */
    fun pruneStaleClaims(maxAgeDays: Long = 180) = mutate { models ->
        val cutoff = Instant.now().minus(maxAgeDays, ChronoUnit.DAYS)
        for (id in models.keys()) {
            val users = models.optJSONObject(id)?.optJSONObject("users") ?: continue
            for (app in users.keys().asSequence().toList()) {
                if (app == appId) continue
                val seen = try {
                    Instant.parse(users.optString(app))
                } catch (e: Exception) {
                    null
                }
                if (seen != null && seen.isBefore(cutoff)) users.remove(app)
            }
        }
    }

    // ---------------------------------------------------------------- registry

    private fun registryFile() = File(root, "registry.json")

    fun models(): JSONObject {
        val f = registryFile()
        if (!f.exists()) return JSONObject()
        return try {
            JSONObject(f.readText()).optJSONObject("models") ?: JSONObject()
        } catch (e: Exception) {
            JSONObject() // A damaged registry reads as empty rather than breaking every app.
        }
    }

    private fun claim(id: String): Boolean {
        var claimed = false
        mutate { models ->
            val entry = models.optJSONObject(id) ?: return@mutate
            (entry.optJSONObject("users") ?: JSONObject().also { entry.put("users", it) }).put(appId, now())
            claimed = true
        }
        return claimed
    }

    private fun register(spec: CatalogModel, recorded: JSONObject) = mutate { models ->
        val now = now()
        val previous = models.optJSONObject(spec.id)
        val users = previous?.optJSONObject("users") ?: JSONObject()
        users.put(appId, now)
        recorded.put("addedAt", now).put("addedBy", appId).put("users", users)
        if (spec.source == "sdk") {
            val apps = previous?.optJSONArray("sdkApps") ?: JSONArray()
            if ((0 until apps.length()).none { apps.optString(it) == appId }) apps.put(appId)
            recorded.put("sdkApps", apps)
        }
        models.put(spec.id, recorded)
    }

    /** Read-modify-write under `.registry.lock`, written to a temp file and renamed. */
    @Synchronized
    private fun mutate(change: (JSONObject) -> Unit) {
        RandomAccessFile(File(root, ".registry.lock"), "rw").use { raf ->
            raf.channel.lock().use {
                val reg = try {
                    if (registryFile().exists()) JSONObject(registryFile().readText()) else JSONObject()
                } catch (e: Exception) {
                    JSONObject()
                }
                val models = reg.optJSONObject("models") ?: JSONObject()
                change(models)
                reg.put("version", 1).put("models", models)
                val tmp = File(root, "registry.json.${java.util.UUID.randomUUID()}.tmp")
                java.io.FileOutputStream(tmp).use { out ->
                    out.write(reg.toString(2).toByteArray())
                    out.fd.sync() // On disk before the rename, so a power cut can't leave an empty registry.
                }
                Files.move(tmp.toPath(), registryFile().toPath(), StandardCopyOption.REPLACE_EXISTING, StandardCopyOption.ATOMIC_MOVE)
            }
        }
    }

    private fun filesPresent(spec: CatalogModel, entry: JSONObject): Boolean {
        if (spec.source == "sdk") return entry.optBoolean("sdkReady") && pathOf(spec.id).isDirectory
        val files = entry.optJSONObject("files") ?: return false
        return spec.files.all { f ->
            val rec = files.optJSONObject(f.name)
            rec != null && pathOf(spec.id, f.name).let { it.exists() && it.length() == rec.optLong("bytes", -1) }
        }
    }

    // ---------------------------------------------------------------- files

    private fun deleteDir(id: String) {
        val dir = pathOf(id)
        if (!dir.exists()) return
        RandomAccessFile(File(dir, ".download.lock"), "rw").use { raf ->
            val lock = try {
                raf.channel.tryLock()
            } catch (e: OverlappingFileLockException) {
                null
            } ?: return // Another app is installing it; it registers the files when done.
            try {
                dir.listFiles()?.filter { it.name != ".download.lock" }?.forEach { it.deleteRecursively() }
            } finally {
                lock.release()
            }
        }
        File(dir, ".download.lock").delete()
        dir.delete() // Not recursive: leaves anything an install started since.
    }

    private fun deletePartials(id: String) {
        val dir = pathOf(id)
        dir.listFiles()?.filter { it.name.endsWith(".part") }?.forEach { it.delete() }
        if (!models().has(id)) dir.listFiles()?.filter { it.name != ".download.lock" }?.forEach { it.deleteRecursively() }
    }

    /** Resumable download through `<dest>.part`, verified by SHA-256 when known. */
    private fun download(f: CatalogFile, dest: File, cancel: CancelSignal, progress: (Long) -> Unit) {
        val part = File(dest.path + ".part")
        var existing = if (part.exists()) part.length() else 0L
        val conn = URL(f.url).openConnection() as HttpURLConnection
        cancel.onCancel = { conn.disconnect() }
        try {
            conn.instanceFollowRedirects = true
            conn.connectTimeout = 30_000
            conn.readTimeout = 60_000 // A stalled server fails the download instead of holding the lock forever.
            // The checksum and the Range offsets are of the file itself, never a compressed body.
            conn.setRequestProperty("Accept-Encoding", "identity")
            headersFor(f).forEach { (k, v) -> conn.setRequestProperty(k, v) }
            if (existing > 0) conn.setRequestProperty("Range", "bytes=$existing-")
            log("${f.name}: downloading from ${conn.url.host}${if (existing > 0) ", resuming at $existing bytes" else ""}")
            val code = conn.responseCode
            log("${f.name}: HTTP $code")
            if (code != 416) {
                if (code != 200 && code != 206) {
                    throw IOException(
                        if (code == 401 || code == 403) "HTTP $code: this model needs its licence accepted and an access token"
                        else "HTTP $code for ${f.name}"
                    )
                }
                if (code == 200) existing = 0 // The server ignored the range.
                var received = existing
                java.io.FileOutputStream(part, existing > 0).use { out ->
                    conn.inputStream.use { input ->
                        val buf = ByteArray(1 shl 16)
                        var last = 0L
                        while (true) {
                            if (cancel.cancelled) throw DownloadCancelled()
                            val n = input.read(buf)
                            if (n < 0) break
                            out.write(buf, 0, n)
                            received += n
                            onNetworkBytes(n.toLong())
                            val now = System.currentTimeMillis()
                            if (now - last > 200) {
                                last = now
                                progress(received)
                            }
                        }
                    }
                }
                progress(received)
            }
            log("${f.name}: checking SHA-256")
            verify(f, part)
            log("${f.name}: checksum ok")
            Files.move(part.toPath(), dest.toPath(), StandardCopyOption.REPLACE_EXISTING)
        } catch (e: DownloadCancelled) {
            throw e
        } catch (e: IOException) {
            if (cancel.cancelled) throw DownloadCancelled()
            throw e
        } finally {
            cancel.onCancel = null
            conn.disconnect()
        }
    }

    private fun verify(f: CatalogFile, file: File) {
        val want = f.sha256 ?: return
        val got = sha256(file)
        if (got != want) {
            file.delete()
            throw ChecksumMismatch(f.name)
        }
    }

    // ---------------------------------------------------------------- siblings

    private fun siblingFiles(): List<SiblingFile> = try {
        siblings?.listAll() ?: emptyList()
    } catch (e: Exception) {
        emptyList()
    }

    private fun matches(f: CatalogFile, s: SiblingFile) =
        (f.bytes == null || f.bytes == s.bytes) && (f.sha256 == null || s.sha256 == null || f.sha256 == s.sha256)

    private fun copyFromSibling(id: String, f: CatalogFile, dest: File, listed: List<SiblingFile>, cancel: CancelSignal): Boolean {
        val s = siblings ?: return false
        val part = File(dest.path + ".part")
        val all = try {
            s.authorities()
        } catch (e: Exception) {
            emptyList()
        }
        val order = (listed.filter { it.modelId == id && it.file == f.name && matches(f, it) }.map { it.authority } + all).distinct()
        for (authority in order) {
            if (cancel.cancelled) throw DownloadCancelled()
            try {
                s.copy(authority, id, f.name, part)
                if (cancel.cancelled) {
                    part.delete()
                    throw DownloadCancelled()
                }
                verify(f, part)
                Files.move(part.toPath(), dest.toPath(), StandardCopyOption.REPLACE_EXISTING)
                return true
            } catch (e: DownloadCancelled) {
                throw e
            } catch (e: Exception) {
                part.delete() // That sibling doesn't have it (or it was damaged); try the next, then the network.
            }
        }
        return false
    }

    private fun copySdkFromSibling(id: String, dir: File, cancel: CancelSignal): Boolean {
        val s = siblings ?: return false
        val byAuthority = siblingFiles().filter { it.modelId == id }.groupBy { it.authority }
        for ((authority, files) in byAuthority) {
            if (cancel.cancelled) throw DownloadCancelled()
            try {
                for (f in files) {
                    val part = File(dir, f.file + ".part")
                    s.copy(authority, id, f.file, part)
                    if (part.length() != f.bytes) throw IOException("short copy")
                    Files.move(part.toPath(), File(dir, f.file).toPath(), StandardCopyOption.REPLACE_EXISTING)
                }
                return true
            } catch (e: Exception) {
                // The folder was empty before: remove everything this attempt wrote.
                dir.listFiles()?.filter { !it.name.startsWith(".") }?.forEach { it.deleteRecursively() }
            }
        }
        return false
    }

    companion object {
        /** `noBackupFilesDir/shared-models`: gigabytes of re-downloadable weights stay out of Auto Backup. */
        fun storeDir(context: Context): File = File(context.noBackupFilesDir, "shared-models").apply { mkdirs() }

        /** The store for this app, with sibling copy, reading the catalog from the app's `base/models.json` asset. */
        fun open(
            context: Context,
            offline: () -> Boolean = { false },
            headersFor: (CatalogFile) -> Map<String, String> = { emptyMap() },
            onNetworkBytes: (Long) -> Unit = {},
            catalog: ModelCatalog = ModelCatalog.fromAsset(context),
            log: (String) -> Unit = {},
        ) = SharedModelStore(
            storeDir(context),
            context.packageName,
            catalog,
            // No provider in the manifest (a test, or a misconfigured app): this app alone, no sibling copy.
            runCatching { AndroidSiblings(context, BaseModelsProvider.discoveryAction(context)) }.getOrNull(),
            offline,
            headersFor,
            onNetworkBytes,
            log,
        )

        fun sha256(file: File): String {
            val md = MessageDigest.getInstance("SHA-256")
            file.inputStream().use { input ->
                val buf = ByteArray(1 shl 20)
                while (true) {
                    val n = input.read(buf)
                    if (n < 0) break
                    md.update(buf, 0, n)
                }
            }
            return md.digest().joinToString("") { "%02x".format(it) }
        }

        private fun now() = Instant.now().truncatedTo(ChronoUnit.MILLIS).toString()

        private fun dirSize(dir: File): Long = dir.walkTopDown().filter { it.isFile && !it.name.startsWith(".") }.sumOf { it.length() }
    }
}

/** Cancels an [SharedModelStore.ensure]; [discard] (wipe) also deletes the partial download. */
class CancelSignal {
    @Volatile
    var cancelled = false
        private set

    @Volatile
    var discard = false

    @Volatile
    internal var onCancel: (() -> Unit)? = null

    fun cancel(discard: Boolean = false) {
        this.discard = this.discard || discard
        cancelled = true
        onCancel?.invoke()
    }
}

class DownloadCancelled : Exception("Download cancelled")

class OfflineException(name: String) :
    Exception("$name isn't on this device yet, and \"never go online\" is on. Turn it off to download it once.")

class ChecksumMismatch(file: String) :
    IOException("The download of $file was damaged (checksum mismatch), so it was thrown away. Try again.")

/** The shared catalog (catalog/models.json in the base platform). */
class ModelCatalog(val all: List<CatalogModel>) {
    private val byId = all.associateBy { it.id }
    fun byId(id: String) = byId[id]

    companion object {
        fun parse(json: String): ModelCatalog {
            val arr = JSONObject(json).getJSONArray("models")
            return ModelCatalog((0 until arr.length()).map { CatalogModel.parse(arr.getJSONObject(it)) })
        }

        /** The catalog an app ships as the asset `base/models.json` (synced from the base platform). */
        fun fromAsset(context: Context) = parse(context.assets.open("base/models.json").bufferedReader().use { it.readText() })
    }
}

data class CatalogModel(
    val id: String,
    val name: String,
    val source: String,
    val platforms: Set<String>,
    val files: List<CatalogFile>,
    val sdkKey: String?,
    val sdkBundled: Boolean,
    val approxBytes: Long?,
) {
    val bytes: Long get() = files.sumOf { it.bytes ?: 0L }.takeIf { it > 0 } ?: (approxBytes ?: 0L)

    companion object {
        fun parse(o: JSONObject): CatalogModel {
            val files = o.optJSONArray("files") ?: JSONArray()
            val platforms = o.optJSONArray("platforms") ?: JSONArray()
            val sdk = o.optJSONObject("sdk")
            return CatalogModel(
                id = o.getString("id"),
                name = o.optString("name", o.getString("id")),
                source = o.optString("source", "file"),
                platforms = (0 until platforms.length()).map { platforms.getString(it) }.toSet(),
                files = (0 until files.length()).map { i ->
                    val f = files.getJSONObject(i)
                    CatalogFile(
                        f.getString("name"),
                        f.getString("url"),
                        if (f.isNull("sha256")) null else f.optString("sha256").ifEmpty { null },
                        if (f.has("bytes") && !f.isNull("bytes")) f.getLong("bytes") else null,
                    )
                },
                sdkKey = sdk?.optString("key"),
                sdkBundled = sdk?.optBoolean("bundled", false) ?: false,
                approxBytes = if (o.has("approxBytes")) o.optLong("approxBytes") else null,
            )
        }
    }
}

data class CatalogFile(val name: String, val url: String, val sha256: String?, val bytes: Long?)

/** One complete file a sibling app can hand over. */
data class SiblingFile(val authority: String, val modelId: String, val file: String, val bytes: Long, val sha256: String?)

/** Other apps of the vendor on this device that share their models (Android). */
interface SiblingSource {
    fun authorities(): List<String>
    fun listAll(): List<SiblingFile>
    fun copy(authority: String, modelId: String, file: String, dest: File): Long
}
